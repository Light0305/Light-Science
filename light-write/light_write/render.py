"""references.bib 回填渲染（生成物）。

纪律（草案 §1.4 / 约束 3/15）：bib 只能由本渲染器从 references.lock 的
verified 快照条目生成；文件头带 GENERATED 标记与 lock 条目集哈希；
手改 bib → 与重算内容不符 → validate 报错（整条回退重渲染，不做局部修补）。
"""

from __future__ import annotations

import re

from .util import component_hash

BIB_HEADER_MARK = "GENERATED by light-write"


def lock_entries_hash(entries) -> str:
    """lock 条目集哈希：覆盖决定 bib 内容的全部字段。"""
    body = [
        {
            "key": e.get("key"),
            "entry_id": e.get("entry_id"),
            "doi": e.get("doi"),
            "title": e.get("title"),
            "authors": e.get("authors"),
            "year": e.get("year"),
            "venue": e.get("venue"),
            "entry_type": e.get("entry_type"),
        }
        for e in entries or []
    ]
    return component_hash(body)


def _bib_escape(text) -> str:
    return str(text or "").replace("{", "").replace("}", "").strip()


def _entry_type(entry) -> str:
    t = (entry.get("entry_type") or "").lower()
    if "proceedings" in t or "conference" in t:
        return "inproceedings"
    if "book" in t:
        return "book"
    return "article"


def render_bib(entries) -> str:
    lines = [
        f"% {BIB_HEADER_MARK} — do not edit by hand; regenerate from references.lock.json",
        f"% lock_entries_hash: {lock_entries_hash(entries)}",
        "",
    ]
    for e in entries or []:
        etype = _entry_type(e)
        venue_field = "booktitle" if etype == "inproceedings" else "journal"
        fields = []
        authors = e.get("authors") or []
        if authors:
            fields.append(("author", " and ".join(str(a) for a in authors)))
        if e.get("title"):
            fields.append(("title", _bib_escape(e["title"])))
        if e.get("venue"):
            fields.append((venue_field, _bib_escape(e["venue"])))
        if e.get("year") is not None:
            fields.append(("year", str(e["year"])))
        if e.get("doi"):
            fields.append(("doi", str(e["doi"])))
        lines.append(f"@{etype}{{{e['key']},")
        for i, (k, v) in enumerate(fields):
            comma = "," if i < len(fields) - 1 else ""
            lines.append(f"  {k} = {{{v}}}{comma}")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


_KEY_STOPWORDS = {"a", "an", "the"}


def cite_key_for(entry, taken: set) -> str:
    """生成 cite key：一作姓（ASCII 化）+ 年份 + 题名首实词；冲突加后缀。

    去重按 Literature 条目 ID 归一（约束 3），不按键字符串——同一条目
    在锁内只出现一次，故 taken 冲突只来自不同条目的同名 key。
    """
    import unicodedata

    authors = entry.get("authors") or []
    surname = ""
    if authors:
        surname = str(authors[0]).strip().split()[-1]
        surname = unicodedata.normalize("NFKD", surname)
        surname = surname.encode("ascii", "ignore").decode("ascii")
        surname = re.sub(r"[^A-Za-z]", "", surname).lower()
    year = str(entry.get("year") or "nd")
    word = ""
    for w in re.findall(r"[A-Za-z]+", entry.get("title") or ""):
        if w.lower() not in _KEY_STOPWORDS:
            word = w.lower()
            break
    base = f"{surname}{year}-{word}" if word else f"{surname}{year}"
    key = base
    n = 2
    while key in taken:
        key = f"{base}-{n}"
        n += 1
    taken.add(key)
    return key
